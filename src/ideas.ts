/** Берём случайный элемент, избегая тех, чьё название встречалось в недавних постах. */
export function pickAvoiding(list: string[], recentTopics: string[], window = 12): string {
  const recent = recentTopics.slice(0, window).join(" | ");
  const fresh = list.filter((x) => !recent.includes(x));
  const pool = fresh.length ? fresh : list;
  return pool[Math.floor(Math.random() * pool.length)];
}
