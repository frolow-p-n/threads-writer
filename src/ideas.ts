/**
 * Берём случайный элемент, избегая тех, чьё название встречалось в recentTopics (окно `window`
 * элементов) и в exclude (то, что уже пробовали в текущей серии попыток, без окна).
 */
export function pickAvoiding(list: string[], recentTopics: string[], window = 12, exclude: string[] = []): string {
  const recent = recentTopics.slice(0, window).join(" | ");
  const fresh = list.filter((x) => !recent.includes(x) && !exclude.includes(x));
  if (fresh.length) return fresh[Math.floor(Math.random() * fresh.length)];
  // Пул в окне исчерпан: допускаем повтор из истории, но не то, что уже пробовали в этой серии попыток.
  const notExcluded = list.filter((x) => !exclude.includes(x));
  const pool = notExcluded.length ? notExcluded : list;
  return pool[Math.floor(Math.random() * pool.length)];
}
